# --- ۱. خوش‌آمد ---
name = "سعید"
city = "تهران"
print(f"سلام {name}! به {city} خوش آمدید.")

# --- ۲. مستطیل ---
length = 10
width = 5
area = length * width
perimeter = 2 * (length + width)
print(f"مساحت: {area} | محیط: {perimeter}")

# --- ۳. دما ---
celsius = 30
fahrenheit = celsius * 9 / 5 + 32
print(f"{celsius}°C = {fahrenheit}°F")

# --- ۴. type ---
s = "hello"
n = 42
f = 3.14
print(type(s), type(n), type(f))
