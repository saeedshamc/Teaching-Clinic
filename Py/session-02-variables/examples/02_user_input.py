# input() برای گرفتن متن از کاربر استفاده می‌شود.
name = input("نام شما چیست؟ ")

# چون input() همیشه متن برمی‌گرداند، باید آن را به عدد تبدیل کنیم.
age = int(input("سن شما چند است؟ "))

# چاپ پیام با استفاده از قالب‌بندی متن
print(f"سلام {name}! سال بعد سن شما {age + 1} می‌شود.")
