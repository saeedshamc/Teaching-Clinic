print("سن:", age)
print("قد:", height)
print("دانشجو:", is_student)

# بررسی نوع داده‌ها
print("نوع name:", type(name))
print("نوع age:", type(age))
print("نوع height:", type(height))
print("نوع is_student:", type(is_student))
