# ۱. یک تا ده
for i in range(1, 11):
    print(i, end=" ")
print()

# ۲. جمع
total = 0
for i in range(1, 101):
    total += i
print("جمع:", total)

# ۳. زوج‌ها
for i in range(2, 21, 2):
    print(i, end=" ")
print()

# ۴. شمارش معکوس
n = 5
while n >= 1:
    print(n)
    n -= 1
