# هدف: با filter فقط نام‌های بلندتر از ۳ حرف را نگه دارید.
# ============================================================

names = ["علی", "مینا", "سعید", "آوا"]
long_names = list(filter(lambda name: len(name) > 3, names))
print(long_names)
