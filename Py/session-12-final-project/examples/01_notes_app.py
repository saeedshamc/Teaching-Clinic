notes = []

# برای اجرای بدون تعامل، برنامه به‌صورت خودکار یک نمونه یادداشت اضافه می‌کند.
notes.append("یادداشت نمونه")

while True:
    print("\nانتخاب کنید:")
    print("1) افزودن یادداشت")
    print("2) نمایش یادداشت‌ها")
    print("3) خروج")

    choice = input("انتخاب شما: ")

    if choice == "1":
        note = input("یادداشت خود را وارد کنید: ")
        notes.append(note)
        print("یادداشت اضافه شد.")
    elif choice == "2":
        if not notes:
            print("هنوز یادداشتی وجود ندارد.")
        else:
            print("یادداشت‌های شما:")
            for note in notes:
                print("-", note)
    elif choice == "3":
        print("خروج از برنامه.")
        break
    else:
        print("انتخاب نامعتبر")
