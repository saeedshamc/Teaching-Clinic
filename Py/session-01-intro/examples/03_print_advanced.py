# ۱. چاپ چند آیتم با فاصله (پیش‌فرض)
print("سلام", "دنیا", "!")

# ۲. تغییر جداکننده با پارامتر sep
print("سلام", "دنیا", "!", sep="-")
print("2024", "07", "26", sep="/")
print("Python", "یک", "زبان", "عالی", "است", sep=" | ")

# ۳. تغییر کاراکتر پایانی با پارامتر end
# پیش‌فرض: end="\n" (رفتن به خط بعد)
print("این خط", end=" ")
print("ادامه همان خط است.")

# ۴. چاپ خط خالی
print()  # فقط یک خط خالی

# ۵. ترکیب sep و end
print("یک", "دو", "سه", sep="-", end=" | ")
print("چهار", "پنج", "شش", sep="-")

# ۶. چاپ کاراکترهای ویژه
print("خط اول\nخط دوم")  # \n = رفتن به خط بعد
print("با\tتب")            # \t = تب (فاصله بزرگ)
print('او گفت: "سلام!"')  # گیومه داخل گیومه

# ۷. چاپ چند خط با یک دستور
print("""
این یک متن
چند خطی است
که راحت چاپ می‌شود.
""")
