# تمرین جلسه ۳
# هدف: عددی از کاربر بگیرد و بگوید زوج است یا فرد.
# ============================================================

number = int(input("یک عدد وارد کنید: "))

if number % 2 == 0:
    print("عدد زوج است.")
else:
    print("عدد فرد است.")
