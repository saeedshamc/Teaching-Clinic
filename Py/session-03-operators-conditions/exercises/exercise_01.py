# ۱. زوج/فرد
n = 14
print(f"{n} {'زوج' if n % 2 == 0 else 'فرد'} است")

# ۲. بزرگ‌ترین دو عدد
a, b = 10, 25
if a > b:
    print("بزرگ‌تر:", a)
else:
    print("بزرگ‌تر:", b)

# ۳. فصل
month = 5
if month in (1, 2, 3):
    print("بهار")
elif month in (4, 5, 6):
    print("تابستان")
elif month in (7, 8, 9):
    print("پاییز")
else:
    print("زمستان")

# ۴. ماشین‌حساب
x, y, op = 10, 3, "+"
if op == "+":
    print(x + y)
elif op == "-":
    print(x - y)
elif op == "*":
    print(x * y)
elif op == "/":
    print(x / y if y != 0 else "تقسیم بر صفر")
