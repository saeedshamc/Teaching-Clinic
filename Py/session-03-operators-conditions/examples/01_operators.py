x = 10
y = 3

print("جمع:", x + y)
print("تفریق:", x - y)
print("ضرب:", x * y)
print("تقسیم:", x / y)
print("باقی‌مانده:", x % y)

print("برابر است؟", x == y)
print("بزرگتر است؟", x > y)
print("کوچک‌تر یا برابر است؟", x <= y)
