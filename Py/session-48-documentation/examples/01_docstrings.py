def add(a: int, b: int) -> int:
    """دو عدد را با هم جمع می‌کند.

    Args:
        a: عدد اول
        b: عدد دوم
    Returns:
        حاصل جمع
    """
    return a + b

print(add(2, 3))
print("--- docstring ---")
print(add.__doc__)
