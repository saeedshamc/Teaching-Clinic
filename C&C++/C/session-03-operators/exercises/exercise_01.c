/*
 * تمرین ۱ — حدس خروجی عبارت‌ها
 * خروجی هر printf را قبل از اجرا حدس بزنید، سپس برنامه را اجرا و مقایسه کنید.
 */

#include <stdio.h>

int main(void) {
    printf("10 / 3 = %d\n", 10 / 3);
    printf("10 %% 3 = %d\n", 10 % 3);
    printf("(3 + 4) * 2 = %d\n", (3 + 4) * 2);
    printf("3 + 4 * 2 = %d\n", 3 + 4 * 2);
    printf("10 > 5 && 3 < 2 = %d\n", 10 > 5 && 3 < 2);
    printf("!(10 > 5) = %d\n", !(10 > 5));
    return 0;
}
