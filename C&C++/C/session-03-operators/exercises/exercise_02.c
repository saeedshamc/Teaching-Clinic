/*
 * تمرین ۲ — جداسازی ارقام یک عدد سه‌رقمی
 * مثال: ورودی 357 → خروجی: 3 5 7
 * راهنمایی: رقم یکان = n % 10 ; سپس n = n / 10
 */

#include <stdio.h>

int main(void) {
    int n = 357;
    int d1, d2, d3;

    /* رقم یکان */
    d1 = n % 10;
    n = n / 10;

    /* رقم دهگان */
    d2 = n % 10;
    n = n / 10;

    /* رقم صدگان */
    d3 = n % 10;

    printf("ارقام: %d %d %d\n", d3, d2, d1);
    return 0;
}
