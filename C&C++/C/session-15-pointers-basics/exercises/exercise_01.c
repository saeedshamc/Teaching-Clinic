/*
 * تمرین ۱ — تغییر مقدار از طریق اشاره‌گر
 * TODO: اشاره‌گر p را به a بدهید، مقدار را از طریق *p تغییر دهید و چاپ کنید.
 */

#include <stdio.h>

int main(void) {
    int a = 5;
    int *p = &a;   /* p به a اشاره می‌کند */

    printf("قبل: a = %d\n", a);

    *p = 100;      /* مقدار a را از طریق اشاره‌گر عوض کن */

    printf("بعد: a = %d\n", a);   /* باید 100 باشد */
    return 0;
}
