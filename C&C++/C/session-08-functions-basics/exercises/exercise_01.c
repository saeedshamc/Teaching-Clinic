#include <stdio.h>

/* TODO: تابع square(int n) را بنویسید که n*n را برگرداند */
/* راهنمایی: برای اینکه اسکلت قابل کامپایل باشد، یک پیاده‌سازی ساده گذاشته‌ایم؛
   اول خودتان سعی کنید آن را بنویسید و بعد جواب را با راه‌حل مقایسه کنید. */
int square(int n) {
    return n * n;
}

int main(void) {
    printf("مربع ۵ = %d\n", square(5));
    printf("مربع ۷ = %d\n", square(7));
    printf("مربع ۱۲ = %d\n", square(12));
    return 0;
}
