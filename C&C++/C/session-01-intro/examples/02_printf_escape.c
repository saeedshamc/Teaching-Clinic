/*
 * جلسه ۱ — شخصیت‌های فرار (Escape Sequences) در printf
 * \n  خط جدید   \t  تب (فاصلهٔ افقی)   \\  بک‌اسلش   \"  علامت نقل‌قول
 */

#include <stdio.h>

int main(void) {
    /* \n یعنی برو به خط بعد */
    printf("خط اول\nخط دوم\n");

    /* \t یک تب می‌سازد */
    printf("نام:\tعلی\nسن:\t۲۵\n");

    /* چاپ بک‌اسلش و نقل‌قول با \\ و \" */
    printf("مسیر: C:\\c-course\n");
    printf("می‌گفت: \"سلام!\"\n");

    return 0;
}
