// 02_comments_and_include.cpp — کامنت‌ها، include و چند شکل چاپ
// در C++ سه چیز را در همان خط اول کد می‌بینیم: دستور پیش‌پردازنده، تابع main و std::cout.

#include <iostream>
#include <string>  // برای استفاده از std::string (رشتهٔ متنی) — در جلسهٔ ۱۰ کامل می‌شود

/*
 * این یک کامنت چندخطی است و با ستاره و اسلش شروع و با اسلش و ستاره تمام می‌شود.
 * نکتهٔ مهم: کامنت‌های بلوکی را نمی‌توان تودرتو نوشت؛ اولین پایان کامنت، همه‌چیز را می‌بندد.
 * اگر وسط کامنت بلوکی علامت پایان کامنت بیاید، کامپایلر خطا می‌دهد.
 */

int main() {
    // ۱) چاپ یک خط با endl (خط را می‌شکند و بافر را هم خالی می‌کند)
    std::cout << "خط اول: سلام!" << std::endl;

    // ۲) چاپ با \n (فقط خط را می‌شکند؛ کمی سریع‌تر از endl)
    std::cout << "خط دوم: هنوز C++ است؟\n";

    // ۳) زنجیرهٔ چاپ: هر << خروجی قبلی را ادامه می‌دهد
    std::string name = "برنامه‌نویس";
    std::cout << "خط سوم: " << name << " خوش آمدی. " << 2 + 2 << "\n";

    // ۴) یک برنامهٔ درست، مقدار ۰ برمی‌گرداند
    return 0;
}
