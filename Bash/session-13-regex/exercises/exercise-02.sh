#!/usr/bin/env bash

# تمرین ۲: اعتبارسنجی پسورد
# هدف: یک اسکریپت بنویسید که:
# 1. یک پسورد از کاربر بگیرد
# 2. با regex بررسی کند:
#    - حداقل 8 کاراکتر
#    - حداقل یک حرف بزرگ
#    - حداقل یک حرف کوچک
#    - حداقل یک عدد
# 3. نتیجه اعتبارسنجی را چاپ کند

# راه‌حل:
read -s -p "لطفاً یک پسورد وارد کنید: " PASSWORD
echo

# بررسی طول
if [ ${#PASSWORD} -lt 8 ]; then
    echo "خطا: پسورد باید حداقل 8 کاراکتر باشد"
    exit 1
fi

# بررسی حرف بزرگ
if ! [[ $PASSWORD =~ [A-Z] ]]; then
    echo "خطا: پسورد باید حداقل یک حرف بزرگ داشته باشد"
    exit 1
fi

# بررسی حرف کوچک
if ! [[ $PASSWORD =~ [a-z] ]]; then
    echo "خطا: پسورد باید حداقل یک حرف کوچک داشته باشد"
    exit 1
fi

# بررسی عدد
if ! [[ $PASSWORD =~ [0-9] ]]; then
    echo "خطا: پسورد باید حداقل یک عدد داشته باشد"
    exit 1
fi

echo "پسورد معتبر است!"
