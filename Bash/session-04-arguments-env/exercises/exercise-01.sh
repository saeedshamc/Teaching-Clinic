#!/usr/bin/env bash

# تمرین ۱: اسکریپت سلام با آرگومان
# هدف: یک اسکریپت بنویسید که:
# 1. یک نام را به عنوان آرگومان بگیرد
# 2. اگر آرگومان داده نشده، پیام خطا نمایش دهد و خارج شود
# 3. پیام سلام شخصی‌سازی شده چاپ کند

# راه‌حل:
# بررسی اینکه آیا آرگومان داده شده است
if [ $# -eq 0 ]; then
    echo "خطا: هیچ آرگومانی داده نشده است"
    echo "استفاده: $0 <نام>"
    exit 1
fi

NAME=$1

# بررسی اینکه آیا آرگومان خالی نیست
if [ -z "$NAME" ]; then
    echo "خطا: آرگومان نمی‌تواند خالی باشد"
    exit 1
fi

echo "سلام، $NAME! خوش آمدی به دوره آموزشی Bash."
