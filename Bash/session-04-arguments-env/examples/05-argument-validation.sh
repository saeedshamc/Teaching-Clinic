#!/usr/bin/env bash

# بررسی اینکه آیا آرگومان داده شده است
if [ $# -eq 0 ]; then
    echo "خطا: هیچ آرگومانی داده نشده است"
    echo "استفاده: $0 <نام>"
    exit 1
fi

NAME=$1

# بررسی اینکه آیا آرگومان خالی نیست
if [ -z "$NAME" ]; then
    echo "خطا: آرگومان نمی‌تواند خالی باشد"
    exit 1
fi

# بررسی تعداد آرگومان‌ها
if [ $# -gt 1 ]; then
    echo "هشدار: فقط اولین آرگومان استفاده می‌شود"
fi

echo "سلام، $NAME!"
