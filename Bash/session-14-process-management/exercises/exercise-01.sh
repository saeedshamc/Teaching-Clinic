#!/usr/bin/env bash

# تمرین ۱: مانیتورینگ ساده
# هدف: یک اسکریپت بنویسید که:
# 1. یک پروسه sleep ایجاد کند
# 2. هر 2 ثانیه وضعیت آن را چک کند
# 3. بعد از 10 ثانیه آن را خاتمه دهد

# راه‌حل:
# ایجاد پروسه sleep
sleep 30 &
PID=$!

echo "پروسه sleep ایجاد شد با PID: $PID"
echo "مانیتورینگ برای 10 ثانیه..."

# مانیتورینگ برای 5 بار (هر 2 ثانیه)
for i in {1..5}; do
    if ps -p $PID > /dev/null; then
        echo "ثانیه $((i * 2)): پروسه در حال اجراست"
    else
        echo "ثانیه $((i * 2)): پروسه خاتمه یافت"
        break
    fi
    sleep 2
done

# خاتمه پروسه
if ps -p $PID > /dev/null; then
    echo "خاتمه پروسه..."
    kill $PID
    echo "پروسه خاتمه یافت"
fi
