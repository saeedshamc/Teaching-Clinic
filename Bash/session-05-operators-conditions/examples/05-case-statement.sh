#!/usr/bin/env bash

read -p "یک رنگ را وارد کنید (قرمز/آبی/سبز/زرد): " COLOR

case "$COLOR" in
    "قرمز"|"red")
        echo "شما قرمز را انتخاب کردید - رنگ عشق و هیجان!"
        ;;
    "آبی"|"blue")
        echo "شما آبی را انتخاب کردید - رنگ آرامش!"
        ;;
    "سبز"|"green")
        echo "شما سبز را انتخاب کردید - رنگ طبیعت!"
        ;;
    "زرد"|"yellow")
        echo "شما زرد را انتخاب کردید - رنگ خوشبختی!"
        ;;
    *)
        echo "رنگ نامعتبر است"
        ;;
esac
