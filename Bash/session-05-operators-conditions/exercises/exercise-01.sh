#!/usr/bin/env bash

# تمرین ۱: بررسی سن
# هدف: یک اسکریپت بنویسید که:
# 1. سن را از کاربر بگیرد
# 2. بررسی کند که در چه بازه سنی است

# راه‌حل:
read -p "لطفاً سن خود را وارد کنید: " AGE

# بررسی اینکه آیا ورودی عدد است
if ! [[ "$AGE" =~ ^[0-9]+$ ]]; then
    echo "خطا: لطفاً یک عدد معتبر وارد کنید"
    exit 1
fi

if [ $AGE -lt 18 ]; then
    echo "شما نوجوان هستید"
elif [ $AGE -ge 18 ] && [ $AGE -le 30 ]; then
    echo "شما جوان هستید"
elif [ $AGE -ge 31 ] && [ $AGE -le 50 ]; then
    echo "شما میانسال هستید"
else
    echo "شما مسن هستید"
fi
