#!/usr/bin/env bash

# تمرین ۱: مدیریت خطا در فایل
# هدف: یک اسکریپت بنویسید که:
# 1. سعی کند یک فایل را بخواند
# 2. اگر فایل وجود نداشت، پیام خطا دهد و خارج شود
# 3. اگر فایل وجود داشت، محتوای آن را چاپ کند

# راه‌حل:
FILE="/tmp/test_read.txt"

# بررسی وجود فایل
if [ ! -f "$FILE" ]; then
    echo "خطا: فایل '$FILE' وجود ندارد"
    exit 1
fi

# خواندن فایل
if cat "$FILE"; then
    echo -e "\nفایل با موفقیت خوانده شد"
else
    echo "خطا: امکان خواندن فایل وجود ندارد"
    exit 1
fi
