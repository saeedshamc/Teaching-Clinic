#!/usr/bin/env bash

# تمرین ۲: جستجوی فایل
# هدف: یک اسکریپت بنویسید که:
# 1. یک نام فایل را از کاربر بگیرد
# 2. در دایرکتوری جاری و زیردایرکتوری‌ها جستجو کند
# 3. تمام فایل‌هایی که با آن نام مطابقت دارند را لیست کند
# 4. تعداد فایل‌های پیدا شده را چاپ کند

# راه‌حل:
read -p "نام فایل برای جستجو: " FILENAME

if [ -z "$FILENAME" ]; then
    echo "خطا: نام فایل نمی‌تواند خالی باشد"
    exit 1
fi

echo "جستجوی فایل‌های '$FILENAME'..."
echo

COUNT=0
for file in $(find . -name "*$FILENAME*" 2>/dev/null); do
    echo "پیدا شد: $file"
    COUNT=$((COUNT + 1))
done

echo
echo "تعداد فایل‌های پیدا شده: $COUNT"
