#!/usr/bin/env bash

# تمرین ۱: شمارش معکوس
# هدف: یک اسکریپت بنویسید که:
# 1. یک عدد از کاربر بگیرد
# 2. از آن عدد تا 1 شمارش معکوس کند
# 3. در انتها پیام "انفجار!" چاپ کند

# راه‌حل:
read -p "یک عدد وارد کنید: " NUMBER

# بررسی اینکه آیا ورودی عدد است
if ! [[ "$NUMBER" =~ ^[0-9]+$ ]] || [ "$NUMBER" -le 0 ]; then
    echo "خطا: لطفاً یک عدد مثبت معتبر وارد کنید"
    exit 1
fi

echo "شمارش معکوس از $NUMBER:"
for ((i=NUMBER; i>=1; i--)); do
    echo "$i"
    sleep 0.5
done

echo "انفجار!"
