#!/usr/bin/env bash

# تمرین ۱: مدیریت لیست کارها
# هدف: یک اسکریپت بنویسید که:
# 1. یک آرایه از کارها داشته باشد
# 2. کارهای انجام شده را نمایش دهد
# 3. کار جدیدی به آرایه اضافه کند
# 4. یک کار را حذف کند
# 5. لیست نهایی را چاپ کند

# راه‌حل:
# آرایه اولیه کارها
TASKS=("خرید مواد غذایی" "تماس با دوست" "انجام پروژه" "ورزش")

echo "لیست کارهای اولیه:"
for i in "${!TASKS[@]}"; do
    echo "  [$i] ${TASKS[$i]}"
done

# افزودن کار جدید
TASKS+=("خواندن کتاب")
echo -e "\nبعد از افزودن کار جدید:"
for i in "${!TASKS[@]}"; do
    echo "  [$i] ${TASKS[$i]}"
done

# حذف کار (ایندکس 1)
unset TASKS[1]
echo -e "\nبعد از حذف کار ایندکس 1:"
for i in "${!TASKS[@]}"; do
    echo "  [$i] ${TASKS[$i]}"
done

# لیست نهایی
echo -e "\nلیست نهایی کارها:"
for i in "${!TASKS[@]}"; do
    echo "  [$i] ${TASKS[$i]}"
done
