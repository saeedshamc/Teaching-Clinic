#!/usr/bin/env bash

# تعریف آرایه
FRUITS=("سیب" "پرتقال" "موز" "انگور" "هلو")

echo "آرایه میوه‌ها:"
echo "${FRUITS[@]}"

# دسترسی به عناصر
echo -e "\nاولین میوه: ${FRUITS[0]}"
echo "دومین میوه: ${FRUITS[1]}"
echo "سومین میوه: ${FRUITS[2]}"

# تعداد عناصر
echo -e "\nتعداد میوه‌ها: ${#FRUITS[@]}"

# دسترسی به آخرین عنصر
echo "آخرین میوه: ${FRUITS[-1]}"
