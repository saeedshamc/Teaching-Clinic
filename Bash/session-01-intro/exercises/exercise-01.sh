#!/usr/bin/env bash

# تمرین ۱: اسکریپت سلام و احوالپرسی
# هدف: یک اسکریپت بنویسید که:
# 1. از کاربر نام بخواهد
# 2. از کاربر شهر محل زندگی را بخواهد
# 3. پیامی چاپ کند که نام و شهر را در خود دارد

# راه‌حل:
echo "لطفاً نام خود را وارد کنید:"
read NAME

echo "لطفاً شهر محل زندگی خود را وارد کنید:"
read CITY

echo "سلام $NAME! از اینکه در $CITY زندگی می‌کنی خوشحالم."
