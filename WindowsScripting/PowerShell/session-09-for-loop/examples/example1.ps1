# =====================================================================
# جلسه 09 - حلقه For در PowerShell
# =====================================================================
for ($i = 1; $i -le 5; $i++) {
    Write-Host "شماره: $i"
}

Write-Host ""
Write-Host "شمارش معکوس:"
for ($i = 10; $i -ge 1; $i--) {
    Write-Host $i
}

Write-Host ""
Write-Host "فقط اعداد زوج:"
for ($i = 0; $i -le 20; $i += 2) {
    Write-Host $i
}

