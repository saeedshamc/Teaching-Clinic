<?php
// مثال ۱: چاپ اعداد ۱ تا ۱۰
for ($i = 1; $i <= 10; $i++) {
    echo $i . "\n";
}

// مثال ۲: چاپ اعداد زوج ۱ تا ۲۰
for ($i = 2; $i <= 20; $i += 2) {
    echo $i . "\n";
}

// مثال ۳: چاپ اعداد به صورت معکوس
for ($i = 10; $i >= 1; $i--) {
    echo $i . "\n";
}

// مثال ۴: چاپ جدول ضرب
$number = 5;
for ($i = 1; $i <= 10; $i++) {
    echo "$number x $i = " . ($number * $i) . "\n";
}

// مثال ۵: استفاده از چندین متغیر در حلقه
for ($i = 1, $j = 10; $i <= 10; $i++, $j--) {
    echo "i: $i, j: $j\n";
}
?>
