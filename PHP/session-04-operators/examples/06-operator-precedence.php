<?php
$a = 5;
$b = 10;
$c = 2;

// مثال ۱: ضرب قبل از جمع انجام می‌شود
$result1 = $a + $b * $c;
echo "5 + 10 * 2 = $result1\n";  // 25 (10 * 2 = 20, سپس 5 + 20 = 25)

// مثال ۲: استفاده از پرانتز برای تغییر اولویت
$result2 = ($a + $b) * $c;
echo "(5 + 10) * 2 = $result2\n";  // 30

// مثال ۳: مقایسه و منطقی
$x = 5;
$y = 10;
$z = 15;

$result3 = $x < $y && $y < $z;
echo "5 < 10 && 10 < 15: " . var_export($result3, true) . "\n";  // true

// مثال ۴: اولویت AND نسبت به OR
$result4 = true || false && false;
echo "true || false && false: " . var_export($result4, true) . "\n";  // true (&& اول ارزیابی می‌شود)

// مثال ۵: اولویت افزایش نسبت به جمع
$num = 5;
$sum = $num++ + $num;
echo "5++ + 5++: $sum\n";  // 11 (اول 5 + 5 = 10، سپس num = 6)

// برای نتیجه 5 + 6 = 11، باید از پرانتز استفاده کنید
$num2 = 5;
$sum2 = $num2++ + ++$num2;
echo "5++ + ++5: $sum2\n";  // 12 (اول num2=5، سپس num2=6، سپس ++num2=7، 5+7=12)
?>
